<?php

namespace AssetMapperUpdate\Tests\PullRequest;

use AssetMapperUpdate\Model\Bucket;
use AssetMapperUpdate\Model\PackageLinks;
use AssetMapperUpdate\Model\PlannedPullRequest;
use AssetMapperUpdate\Model\Severity;
use AssetMapperUpdate\Model\UpdateType;
use AssetMapperUpdate\PullRequest\ApplyDetails;
use AssetMapperUpdate\PullRequest\Content;
use AssetMapperUpdate\PullRequest\PullRequestState;
use AssetMapperUpdate\Tests\Factory;
use PHPUnit\Framework\TestCase;

final class ContentTest extends TestCase
{
    public function testDependabotStyleTitles(): void
    {
        $this->assertSame('Bump bootstrap from 5.3.0 to 5.3.3', Content::title(self::single()));
        $this->assertSame('Bump 4 importmap packages (minor)', Content::title(self::group()));
    }

    public function testCommitMessagesWithThePrefix(): void
    {
        $this->assertSame('chore(deps): bump bootstrap from 5.3.0 to 5.3.3 in importmap', Content::commitMessage(self::single(), 'chore(deps):'));
        $this->assertSame(
            "bump 4 importmap packages (minor)\n\n- a from 1.0.0 to 1.1.0\n- b from 2.0.0 to 2.3.0\n- c from 0.1.0 to 0.2.0\n- d from 3.1.0 to 3.2.0",
            Content::commitMessage(self::group(), ''),
        );
    }

    public function testMarkerRoundTrip(): void
    {
        $state = PullRequestState::fromBody(Content::body(self::group(), new ApplyDetails(), 'php bin/console'));
        $this->assertEquals(PullRequestState::of(self::group()), $state);
        $this->assertTrue($state?->equals(PullRequestState::of(self::group())));
    }

    public function testMarkerFormatIsStable(): void
    {
        $this->assertSame(
            '<!-- asset-mapper-update {"v":1,"bucket":"patch","updates":[{"name":"bootstrap","from":"5.3.0","to":"5.3.3"}]} -->',
            PullRequestState::of(self::single())->render(),
        );
    }

    public function testIgnoresBodiesWithoutAValidMarker(): void
    {
        $this->assertNull(PullRequestState::fromBody('Bumps stuff'));
        $this->assertNull(PullRequestState::fromBody(null));
        $this->assertNull(PullRequestState::fromBody('<!-- asset-mapper-update {broken -->'));
        $this->assertNull(PullRequestState::fromBody('<!-- asset-mapper-update {"v":2,"bucket":"patch","updates":[]} -->'));
    }

    public function testComparesStatesIndependentOfOrder(): void
    {
        $a = PullRequestState::of(self::group());
        $this->assertTrue($a->equals(new PullRequestState($a->bucket, array_reverse($a->updates))));
        $this->assertFalse($a->equals(new PullRequestState('major', $a->updates)));
    }

    public function testReplacesTheMarker(): void
    {
        $state = PullRequestState::of(self::single());
        $closed = $state->withClosedByAction()->replaceIn(Content::body(self::single(), new ApplyDetails(), 'php bin/console'));
        $this->assertTrue(PullRequestState::fromBody($closed)?->closedByAction);
        $this->assertSame(1, substr_count($closed, 'asset-mapper-update {'));
        $this->assertStringContainsString($state->render(), $state->replaceIn('no marker'));
    }

    public function testBodyWithTableLinksEntriesAndFooter(): void
    {
        $text = Content::body(self::single(), new ApplyDetails(), 'php bin/console');
        $this->assertStringContainsString('Bumps **bootstrap** from 5.3.0 to 5.3.3 in `importmap.php`.', $text);
        $this->assertStringContainsString('| [bootstrap](https://www.npmjs.com/package/bootstrap) | 5.3.0 | 5.3.3 | patch |', $text);
        $this->assertStringContainsString('[release notes](https://github.com/twbs/bootstrap/releases)', $text);
        $this->assertStringContainsString('- `bootstrap/dist/css/bootstrap.min.css`', $text);
        $this->assertStringContainsString('`assets/vendor/` is not part of this diff. It is regenerated by `php bin/console importmap:install`.', $text);
    }

    public function testBodyListsAdvisoriesAndWarnsAboutMajors(): void
    {
        $advisory = Factory::advisory('GHSA-qppm-g56g-fpvp', '<= 8.0.20', severity: Severity::Low, summary: 'Turbo Frame responses can restore stale session cookies', cveId: 'CVE-2025-66803');
        $pr = Factory::pr('importmap-updates/security/hotwired-turbo', [Factory::update('@hotwired/turbo', '7.3.0', '8.0.21', Bucket::Security, UpdateType::Major, advisories: [$advisory], crossesMajor: true)]);
        $text = Content::body($pr, new ApplyDetails(), 'php bin/console');
        $this->assertStringContainsString('| @hotwired/turbo | [GHSA-qppm-g56g-fpvp](https://github.com/advisories/GHSA-qppm-g56g-fpvp) (CVE-2025-66803) | low | Turbo Frame responses can restore stale session cookies | `<= 8.0.20` |', $text);
        $this->assertStringContainsString('> [!WARNING]', $text);
        $this->assertStringContainsString('no fixed version exists in 7.x', $text);
    }

    public function testBodyMentionsNewEntriesAndSideEffects(): void
    {
        $text = Content::body(self::single(), new ApplyDetails(['@popperjs/core' => ['version' => '2.11.8']], ['jquery: 3.4.1 → 3.6.0']), 'php bin/console');
        $this->assertStringContainsString('### New entries', $text);
        $this->assertStringContainsString('- `@popperjs/core` 2.11.8', $text);
        $this->assertStringContainsString('- `jquery: 3.4.1 → 3.6.0`', $text);
    }

    private static function single(): PlannedPullRequest
    {
        return Factory::pr('importmap-updates/patch', [Factory::update(
            'bootstrap',
            '5.3.0',
            '5.3.3',
            entries: ['bootstrap', 'bootstrap/dist/css/bootstrap.min.css'],
            links: new PackageLinks('https://www.npmjs.com/package/bootstrap', 'https://github.com/twbs/bootstrap', 'https://github.com/twbs/bootstrap/releases'),
        )]);
    }

    private static function group(): PlannedPullRequest
    {
        return Factory::pr('importmap-updates/minor', [
            Factory::update('a', '1.0.0', '1.1.0', Bucket::Minor, UpdateType::Minor),
            Factory::update('b', '2.0.0', '2.3.0', Bucket::Minor, UpdateType::Minor),
            Factory::update('c', '0.1.0', '0.2.0', Bucket::Minor, UpdateType::Minor),
            Factory::update('d', '3.1.0', '3.2.0', Bucket::Minor, UpdateType::Minor),
        ]);
    }
}
